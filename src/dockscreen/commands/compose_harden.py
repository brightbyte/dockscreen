"""This module implements `docker compose harden` (and `fix`), dockscreen's own command. It prints a compose
override that fixes the problems that have a safe fix.

The compose options before the subcommand (e.g. ["-f", "x.yml"]), which select the project, are the lead_args
of the command line.

The fixes come from the policy (projectfixes). Policy.check_project then runs on the result and reports the
problems that are left.

The function _render writes the difference between a config and its fixed copy as a compose override file.
Compose merges override lists by appending and cannot drop a key by omitting it, so removals use the `!reset`
tag and replaced lists use `!override`. _render writes the values as JSON, which is valid YAML.
"""

import json
import re
import sys
from collections.abc import Iterable
from typing import Any

from dockscreen.commands import helptext
from dockscreen.host.docker import DockerError
from dockscreen.host.runtime import Runtime
from dockscreen.policy import hardening, projectfixes
from dockscreen.policy.finding import Finding, failure_of
from dockscreen.policy.report import Report
from dockscreen.screen import inspect, projectscreening
from dockscreen.screen.screener import Screener
from dockscreen.util import commandline, messages
from dockscreen.util.messages import printable_text


def harden(parent_cli: commandline.CommandLine, runtime: Runtime) -> int:
    """Prints a compose override that fixes the problems that have a safe fix. Exits with 1 if problems
    remain.

    The patch applies to the merged config as dockscreen will run it, with its defaults included. It holds
    only the changes needed on top of that config to pass the audit, and one comment names the defaults that
    dockscreen adds itself. Mount sources outside the project become placeholders for you to edit. The patch
    lists the problems without a safe automatic fix as comments. harden first pulls and builds the images, as
    `up` would, to find the services that need a user of their own.

    Where a user has to be set, harden sets `${UID}:${GID}`, which is your own. So harden checks the result as
    if you gave --allow-me, and the patch says that it needs --allow-me.

    Parameters:
    - parent_cli: the compose command line, with `harden` or `fix` as its command; --allow-me in it makes no
      difference, since this checks the result as if the invoking user gave it either way
    - runtime: the Runtime of the command
    """
    assert parent_cli.cmd in ("harden", "fix")
    try:
        loaded_project = projectscreening.load_project(list(parent_cli.lead_args), runtime)
    except inspect.ProjectRefusal as e:
        for refusal in e.findings:
            messages.print_notice(refusal)
        return 1
    except (DockerError, ValueError) as e:
        messages.print_notice(failure_of(e))
        return 1
    screener = Screener(runtime, is_me_allowed=True)
    static_policy = screener.project_policy(loaded_project.resolved_project)
    for refusal in static_policy.check_daemon(loaded_project.is_remote):
        messages.print_notice(refusal)
        return 1

    static_project = loaded_project.static_project()
    fixed_config = projectfixes.fix_config(static_project, static_policy)
    # the patch as compose would read it, which is the config that runs. Compose interpolates the generated
    # file and makes its paths absolute, so ${UID} or ./ETC in it would read back differently from the checked
    # config
    resolved_config = projectfixes.resolve_config_values(fixed_config, static_policy,
                                                         static_project.directory)
    # the patched project goes through the same stages as `up` would take it through
    check_result = projectscreening.check(loaded_project.with_hardened_definition(resolved_config), screener)
    notes = [hardening.defaults_note()]
    if isinstance(check_result, Report):
        remaining_problems = list(check_result.findings)
        messages.print_notice("the images were not looked at because of the problems below: "
                              "nothing was pulled or built")
    else:
        cleared_project = check_result
        with cleared_project.loaded_project.generated_files(screener.docker.binary) as command:
            decisions = projectscreening.decide(cleared_project, screener, command)
        if decisions.by_service:
            remaining_problems, image_notes = projectfixes.set_image_users(fixed_config, decisions.by_service)
            notes += image_notes
        else:  # nothing could be looked at: pulling or building failed
            remaining_problems = list(decisions.report.findings)

    sys.stdout.write(_render(static_project.definition, fixed_config, remaining_problems, notes=notes))
    for problem in remaining_problems:
        messages.print_notice(f"cannot fix automatically: {problem}")
    return 1 if remaining_problems else 0


_HEADER = "# Generated by `dockscreen harden`. Save as compose.override.yaml, or load it last with -f."
_SAFE_YAML_KEY = re.compile(r"^[A-Za-z0-9_.-]+$")


def _render(original_config: dict[str, Any], fixed_config: dict[str, Any],
            unfixed_problems: Iterable[Finding] = (),
            notes: Iterable[str] = ()) -> str:
    """Renders the compose override that turns original_config into fixed_config, as YAML text.

    original_config: the config compose applies the patch to, as dockscreen will run it (defaults included).
    unfixed_problems and notes become comments.

    The user saves this as a compose file, and much of it is the project's text: mount sources and problems in
    comments, and service names and keys. This escapes the comments (printable_text), so that a newline in
    them cannot end the comment and add keys of the project's choosing, such as `privileged: true`. It also
    quotes names and keys, unless they are plainly safe.
    """
    lines = [_HEADER]
    lines += [f"# note: {printable_text(note)}" for note in notes]
    lines += [f"# edit: {printable_text(note)}" for note in _mount_notes(original_config, fixed_config)]
    lines += [f"# not fixed: {printable_text(problem)}" for problem in unfixed_problems]

    changes = _service_changes(original_config, fixed_config)
    if any("user" in service for service in changes.values()):
        lines.append("# note: user ${UID}:${GID} runs a service as you: dockscreen allows that only with "
                     "--allow-me, and plain docker compose needs UID and GID exported.")
    if not changes:
        return "\n".join([*lines, "services: {}", ""])

    lines.append("services:")
    for name, service in changes.items():
        lines.append(f"  {json.dumps(name)}:")
        lines += [f"    {_yaml_key(key)}: {value}" for key, value in service.items()]
    return "\n".join([*lines, ""])


def _yaml_key(key: str) -> str:
    """Returns key as a YAML mapping key, quoted unless it is plainly safe."""
    return key if _SAFE_YAML_KEY.match(key) else json.dumps(key)


def _mount_notes(original_config: dict[str, Any], fixed_config: dict[str, Any]) -> list[str]:
    """Returns one note for each mount whose source fixed_config replaces with a placeholder."""
    notes = []
    for name, before in original_config.get("services", {}).items():
        after = fixed_config["services"][name]
        for old_mount, new_mount in zip(before.get("volumes", []), after.get("volumes", [])):
            if old_mount.get("source") != new_mount.get("source"):
                notes.append(
                    f"service {name}: mount source {old_mount['source']} was replaced by the placeholder "
                    f"{new_mount['source']}, which compose creates empty; point it at a path inside the "
                    "project")
    return notes


def _service_changes(original_config: dict[str, Any],
                     fixed_config: dict[str, Any]) -> dict[str, dict[str, str]]:
    """Returns {service: {key: rendered YAML value}} for the keys that fixed_config changes in
    original_config.
    """
    changes = {}
    for name, before in original_config.get("services", {}).items():
        after = fixed_config["services"][name]
        service = {
            key: _render_value(after.get(key))
            for key in sorted(set(before) | set(after))
            if before.get(key) != after.get(key)
        }
        if service:
            changes[name] = service
    return changes


def _render_value(value: Any) -> str:
    """Renders value as YAML for the override file, tagged so that it replaces the project's value."""
    if value is None:
        return "!reset null"
    if isinstance(value, list):
        return "!override " + json.dumps(value)
    return json.dumps(value)


def help(name: str) -> helptext.HelpTopic:
    """Returns the help of the command name, from the docstring of harden.

    Parameters:
    - name: the command, as the dispatcher knows it: harden, or its alias fix
    """
    return helptext.command_topic("harden", harden, aliases=("fix",))
